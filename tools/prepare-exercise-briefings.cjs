/* The two newer exercises use the editable text files as their source of truth.
 * No game rules, dynamic selection lists, or author notes become generated text.
 */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const marker = '[DYNAMIC TEXT — selected unit/ability or selection summary]';
const specs = [
    {file: 'hotkey-trainer', source: 'hotkey-training.lua', id: 'tools.hotkeys', pages: ['root', 'race']},
    {file: 'reflex-training', source: 'reflex-training.lua', id: 'skills.reflex', pages: ['root', 'races'], dynamic: 'races'},
];
const output = path.join(root, 'src/generated/exercise-briefings.lua');

function parse(text, spec) {
    text = text.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
    if (!text.includes(`\nSource: src/activities/${spec.source}\n`)) {
        throw new Error(`${spec.file}: missing or mismatched Source field`);
    }
    const sections = [...text.matchAll(/={60}\n([^\n]+)\n={60}\n\n([\s\S]*?)(?=\nYour notes:)/g)];
    if (sections.length !== spec.pages.length) throw new Error(`${spec.file}: expected exactly two briefing pages`);
    const pages = {};
    sections.forEach((section, index) => {
        if (section[1] !== `Selection page ${index + 1}`) throw new Error(`${spec.file}: changed/duplicate page label`);
        let body = section[2].replace(/^\n+|\n+$/g, '');
        if (!body.trim()) throw new Error(`${spec.file}: empty briefing`);
        if (/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/.test(body)) throw new Error(`${spec.file}: unsupported control character`);
        const page = spec.pages[index];
        if (page === spec.dynamic) {
            if (!body.endsWith(marker) || body.split(marker).length !== 2) {
                throw new Error(`${spec.file}: retain the dynamic summary placeholder at the end of page 2`);
            }
            body = body.slice(0, -marker.length); // preserve paragraph spacing before live summary
        } else if (body.includes(marker)) throw new Error(`${spec.file}: unexpected dynamic placeholder`);
        pages[page] = body;
    });
    return pages;
}

function render() {
    const lines = ['-- Generated by tools/prepare-exercise-briefings.cjs. Edit design/exercises/editable/*.txt.',
        'JTG.ExerciseBriefings = {'];
    for (const spec of specs) {
        const file = path.join(root, 'design/exercises/editable', `${spec.file}.txt`);
        const pages = parse(fs.readFileSync(file, 'utf8'), spec);
        lines.push(`    [${JSON.stringify(spec.id)}] = {`);
        for (const page of spec.pages) lines.push(`        ${page} = ${JSON.stringify(pages[page])},`);
        lines.push('    },');
    }
    return lines.concat('}', '').join('\n');
}

function prepare(check = false) {
    const expected = render();
    const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : '';
    if (current.replace(/\r\n/g, '\n') === expected) return false;
    if (check) throw new Error('Briefing text is stale. Run node tools/prepare-exercise-briefings.cjs');
    fs.writeFileSync(output, expected, 'utf8');
    return true;
}

module.exports = {parse, render, prepare, specs, marker};
if (require.main === module) {
    prepare(process.argv.includes('--check'));
    console.log('Passed: authoritative Hotkey/Reflex briefing text matches generated Lua.');
}
