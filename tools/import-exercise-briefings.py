"""Apply edited briefing snapshots to source without rewriting the author files."""
import importlib.util
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
spec=importlib.util.spec_from_file_location('briefing_export',Path(__file__).with_name('export-exercise-briefings.py'))
export=importlib.util.module_from_spec(spec);spec.loader.exec_module(export)
CONSTANTS={'body-blocking':('BODY_BLOCKING_INTRO','Main briefing'),
    'surrounds':('INTRO','Main briefing'),'gargoyle-surrounds':('GARGOYLE_INTRO','Main briefing'),
    'windwalk-pop':('WINDWALK_POP_INTRO','Main briefing'),'mining-micro':('MINING_MICRO_INTRO','Main briefing'),
    'bat-splitting':('INTRO','Main briefing'),'power-building':('POWER_BUILDING_INTRO','Main briefing')}
MARKER='[DYNAMIC TEXT — selected unit/ability or selection summary]'

def quote(text): return json.dumps(text,ensure_ascii=False)

changes=0
for path in sorted((ROOT/'design/exercises/editable').glob('*.txt')):
    if path.stem in {'hotkey-trainer','reflex-training'}:
        continue  # authoritative text is generated by the map build, never regex-imported
    text=path.read_text(encoding='utf-8-sig')
    sections={label.strip():body.strip('\n') for label,body in re.findall(
        r'={60}\n([^\n]+)\n={60}\n\n(.*?)(?=\nYour notes:)',text,re.S)}
    source_path=ROOT/re.search(r'^Source: (.+)$',text,re.M)[1]
    source=source_path.read_text(encoding='utf-8')
    original=source
    if path.stem in CONSTANTS:
        variable,label=CONSTANTS[path.stem]
        pattern=r'(local '+variable+r'\s*=\s*)('+export.EXPRESSION+r')'
        source=re.sub(pattern,lambda match:match[1]+quote(sections[label]),source,count=1)
    if path.stem=='dodging':
        for label,body in sections.items():
            pattern=r'(\b'+re.escape(label)+r'\s*=\s*)('+export.EXPRESSION+r')'
            if label in export.literal(original,'BRIEFING'):
                source=re.sub(pattern,lambda match:match[1]+quote(body),source,count=1)
        templates={
            'Ability disjoin — choose dodger':('disjoin','[chosen projectile]',True),
            'Attack disjoin — choose dodger':('disjoin','[chosen projectile]',False),
            'Area — choose dodge ability':('avoid','[chosen area ability]',False)}
        for label,(verb,placeholder,long) in templates.items():
            if label not in sections: continue
            value=sections[label];before,after=value.split(placeholder,1)
            pattern=r'"Choose which ability you want to use to try to '+verb+r' "\.\.danger\.name\.\.('+export.STRING+r')'
            matches=list(re.finditer(pattern,source))
            selected=next((match for match in matches if ('three stages' in match[0])==long),None)
            if selected:
                source=source[:selected.start()]+quote(before)+'..danger.name..'+quote(after)+source[selected.end():]
    else:
        matches=list(re.finditer(r'(?:\bbody|spec\.body)\s*=\s*('+export.EXPRESSION+r')',source))
        # Replace backwards so source offsets remain valid.
        for index,match in reversed(list(enumerate(matches,1))):
            label=f'Selection page {index}'
            if label not in sections: continue
            body=sections[label]
            if MARKER in body: body=body.split(MARKER,1)[0]
            source=source[:match.start(1)]+quote(body)+source[match.end(1):]
    if source!=original:
        source_path.write_text(source,encoding='utf-8')
        changes+=1
        print(source_path.name)
print(f'Updated {changes} source files; edited author files retained.')
