"""Embed the distributable CustomKeys files as safe preload-sized chunks."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "data"
OUTPUT = ROOT / "src" / "generated" / "custom-keys.lua"
MAX_CHUNK = 700


def chunks_for(path: Path):
    chunks = []
    current = []
    length = 0
    for line in path.read_text(encoding="utf-8").splitlines():
        added = len(line) + (1 if current else 0)
        if current and length + added > MAX_CHUNK:
            chunks.append("\n".join(current))
            current = []
            length = 0
        current.append(line)
        length += len(line) + (1 if len(current) > 1 else 0)
    if current:
        chunks.append("\n".join(current))
    return chunks


def lua_long_string(value: str):
    # Start with one equals sign so an INI section ending in "]" cannot
    # overlap the Lua closing delimiter.
    equals = "="
    while f"]{equals}]" in value:
        equals += "="
    return f"[{equals}[{value}]{equals}]"


entries = []
for layout in ("QWERTY", "QWERTZ"):
    source = SOURCE / f"CustomKeys-Solanum{layout}.txt"
    chunks = chunks_for(source)
    encoded = ",\n            ".join(lua_long_string(chunk) for chunk in chunks)
    entries.append(
        "    {\n"
        f"        filename = \"CustomKeys-Solanum{layout}.txt\",\n"
        f"        layout = \"{layout}\",\n"
        "        chunks = {\n            " + encoded + "\n        },\n"
        "    },"
    )

OUTPUT.parent.mkdir(parents=True, exist_ok=True)
OUTPUT.write_text(
    "-- Generated by tools/prepare-custom-keys.py.\n"
    "JTG = JTG or {}\n\n"
    "JTG.CustomKeyExports = {\n" + "\n".join(entries) + "\n}\n",
    encoding="utf-8",
)
print(f"Prepared {OUTPUT.relative_to(ROOT)}")
